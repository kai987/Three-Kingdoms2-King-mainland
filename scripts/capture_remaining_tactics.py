def main():
    p=argparse.ArgumentParser(description=__doc__);p.add_argument('rom',type=Path);p.add_argument('--ids',type=int,nargs='+',default=list(IDS))
    p.add_argument('--out',type=Path,default=ROOT/'analysis/phase9/runtime');p.add_argument('--compare',type=Path)
    p.add_argument('--death-case',action='store_true',help='Add an original ID1 health1 death-settlement replay')
    p.add_argument('--levelup-case',action='store_true',help='Add an original ID9 XP3490/tier2 level-up and martial-notification replay');a=p.parse_args()
    a.out=a.out.resolve()
    if a.compare:a.compare=a.compare.resolve()
