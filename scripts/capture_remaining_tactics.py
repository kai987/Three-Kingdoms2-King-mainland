def inspect(ram,sram,frame):
    def officer(ident):
        raw=sram[0x3C0+12*ident:0x3C0+12*ident+12]
        return {'officer_id':ident,'record_hex':raw.hex(' ').upper(),'health':raw[0],'martial':raw[1],'loyalty':raw[3],
                'intelligence':raw[2],'residence_raw':raw[5],'experience_u16':raw[6]+256*raw[7],
                'packed_byte11':raw[11],'troops_raw_u16':raw[8]+256*raw[9],
                'troops_low10':raw[8]+256*(raw[9]&3)}
    units=[]
    for slot in range(20):
        ident=ram[0x664+slot]
        if ident==255:continue
        raw=sram[0x3C0+12*ident:0x3C0+12*ident+12]
        units.append({'slot':slot,'officer_id':ident,'x':ram[0x600+slot],'y':ram[0x614+slot],
                      'side_condition_raw':ram[0x628+slot],'condition_raw':ram[0x650+slot],
                      'hundred_troops_cache':ram[0x63C+slot],'AI_strategy_raw':sram[0xFA1+slot],
                      'record_hex':raw.hex(' ').upper(),'health':raw[0],'martial':raw[1],'loyalty':raw[3],
                      'intelligence':raw[2],'residence_raw':raw[5],'experience_u16':raw[6]+256*raw[7],
                      'packed_byte11':raw[11],'troops_raw_u16':raw[8]+256*raw[9],
                      'troops_low10':raw[8]+256*(raw[9]&3)})
    return {'frame':frame,'global_main':ram[0x7A],'nmi_scene':ram[0x78],'battle_state':list(ram[0x500:0x502]),
            'side_0504':ram[0x504],'AP_0505':ram[0x505],'round_0506':ram[0x506],
            'target_0509':ram[0x509],'actor_or_scratch_050A':ram[0x50A],
            'tactic_0543':ram[0x543],'result_0544':ram[0x544],'animation_04C8':ram[0x4C8],
            'report_042C_0433':list(ram[0x42C:0x434]),'resources_0520_0527':list(ram[0x520:0x528]),
            'word_0522':ram[0x522]+256*ram[0x523],'word_0524':ram[0x524]+256*ram[0x525],
            'side_aggregates_0518_051F':list(ram[0x518:0x520]),
            'cache_04D8_04DF':list(ram[0x4D8:0x4E0]),'request_6F8B':sram[0xF8B],
            'proposal_6F8C_6F8F':list(sram[0xF8C:0xF90]),'AI_rng_6F92':sram[0xF92],
            'fixed_rng_0050_0057':list(ram[0x50:0x58]),'world_cursor':list(sram[0xF3F:0xF43]),
            'menu_cursor_0012':ram[0x12],'text_jobs':[ram[0x300],ram[0x304]],'button_0081_0087':[ram[0x81],ram[0x87]],
            'available_tactics':list(ram[0x580:0x590]),'units':units,
            'officer_records':{str(ident):officer(ident)for ident in(8,51,109,131,167,191)},
            'unit_arrays':{hex(base):list(ram[base:base+20])for base in(0x600,0x614,0x628,0x63C,0x650,0x664)}}

def unit(row,slot):return next(x for x in row['units']if x['slot']==slot)

def configuration(tactic):
    caster=(19,14)if tactic==9 else(2,16)
    target_slot=0 if tactic==5 else 1
    target=(18,14)if tactic==9 else(4,16)if tactic in(10,12)else(5,16)
    positions={10:caster,target_slot:target}
    if tactic in(7,14):positions[2]=(5,17)
    if tactic in(10,12):positions[2]=(4,14)
    if tactic==9:positions[2]=(17,14)
    return caster,target_slot,target,positions

