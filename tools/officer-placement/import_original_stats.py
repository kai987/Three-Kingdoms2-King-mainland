#!/usr/bin/env python3
"""Archived virtue-only importer; current campaigns reject this write policy.

Use import_campaign_stats.py for the current charisma/initial-health policy.

Names are joined through the existing reviewed ROM name-glyph identity map,
never by matching portraits, ability values, runtime IDs or roster ordinals.
The reference retains all237 raw records. Reviewed identity coverage is derived
from the map; the original220 bindings remain frozen and Wang Jian is the sole
additional reviewed binding. This archived command cannot overwrite today's
charisma/initial-health policy.

--check validates retained evidence without applying the archived policy; it
does not need a ROM. If supplied, the ROM must match all237 retained records.
The first220-person virtue-import audit is historical evidence, separate from
the current221 reviewed identity bindings, and is never regenerated by check.
"""
import argparse
from copy import deepcopy
from hashlib import sha256
import json
from pathlib import Path
import sys

sys.dont_write_bytecode = True
ROOT = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(ROOT / 'game'))
from officer_stat_sources import (ORIGINAL_RECORD_OFFSET, ORIGINAL_RECORD_SIZE,
                                 ORIGINAL_ROM_SHA256, validate_original_virtue)

BASE_BINDINGS_SHA256 = '3052ca5edf55f60914e71c1e3e4fd51bc9cbd90a23c3da7f68518e6b8fd85110'
WANG_JIAN = 'historical-wang-jian-liaodong'


def reviewed_coverage(identities):
    """Count an explicitly reviewed map; never infer another name binding."""
    records = identities.get('records', [])
    if (identities.get('schema') != 'tk2-portrait-identities-v1'
            or identities.get('rom_sha256') != ORIGINAL_ROM_SHA256
            or not isinstance(records, list) or len(records) != 237
            or [row.get('original_id') for row in records] != list(range(237))):
        raise ValueError('Original237 reviewed identity records differ')
    bound = [row for row in records if row.get('person_id') is not None]
    if len({row['person_id'] for row in bound}) != len(bound):
        raise ValueError('Duplicate original reviewed person binding')
    retained = [row for row in bound if row['person_id'] != WANG_JIAN]
    frozen = json.dumps(retained, ensure_ascii=False, sort_keys=True, separators=(',', ':')).encode('utf-8')
    if len(retained) != 220 or sha256(frozen).hexdigest() != BASE_BINDINGS_SHA256:
        raise ValueError('Frozen original220 identity bindings changed')
    added = [row for row in bound if row['person_id'] == WANG_JIAN]
    if (len(added) != 1 or added[0]['original_id'] != 11 or added[0]['transcribed_name'] != '王建'
            or added[0].get('identity_context', {}).get('public_table_source_row_id') != 'cnblogs-line-0229'):
        raise ValueError('Only reviewed Wang Jian original11 may extend the bindings')
    return dict(original_records=len(records), bound_people=len(bound),
                unbound_original_records=len(records)-len(bound))


def encode(value):
    return json.dumps(value, ensure_ascii=False, indent=2) + '\n'


def verify_retained_reference(rom=None):
    """Read-only proof of current bindings and retained bytes, not a stat import."""
    identity_path = ROOT / 'game/config/portrait-identity-map.json'
    reference_path = ROOT / 'game/config/references/original-officer-stats.json'
    identities = json.loads(identity_path.read_text())
    reference = json.loads(reference_path.read_text())
    people = json.loads((ROOT / 'game/config/campaigns/people.json').read_text())['people']
    coverage = reviewed_coverage(identities)
    if (reference.get('identity_source_sha256') != sha256(identity_path.read_bytes()).hexdigest()
            or any(reference.get(key) != value for key, value in coverage.items())):
        raise ValueError('Retained original source identity coverage/hash differs')
    validate_original_virtue(people, reference, identities)
    if rom is not None:
        if sha256(rom).hexdigest() != ORIGINAL_ROM_SHA256:
            raise ValueError('Different ROM; original reference check stopped')
        for row in reference['records']:
            offset = row['rom_offset']
            if rom[offset:offset + ORIGINAL_RECORD_SIZE] != bytes.fromhex(row['record_hex']):
                raise ValueError('Retained original record bytes differ from ROM')
    # These refer to the first historical220-person import, not to today's
    # extra identity binding or the active SAN14-charisma policy.
    audit = reference['audit']
    historical = dict(changed_people=214, prior_default_changes=89,
                      prior_design_changes=125, unchanged_original_values=6)
    if any(audit.get(key) != value for key, value in historical.items()):
        raise ValueError('Historical first220-person import audit changed')
    return dict(**coverage, policy='retained_evidence_only; current_campaign_stats_unchanged',
                historical_first_import_people=220, historical_first_import_audit=historical)


def import_stats(rom):
    if sha256(rom).hexdigest() != ORIGINAL_ROM_SHA256:
        raise ValueError('Different ROM; original virtue import stopped')
    identity_path = ROOT / 'game/config/portrait-identity-map.json'
    identities = json.loads(identity_path.read_text())
    coverage = reviewed_coverage(identities)
    people_path = ROOT / 'game/config/campaigns/people.json'
    pool = json.loads(people_path.read_text())
    if any('pre_campaign_stat_policy_v1' in person for person in pool['people'].values()):
        raise ValueError('The old virtue-only importer is archived. Use import_campaign_stats.py --check; '
                         'the retained ROM reference must not overwrite the current charisma policy.')
    records, differences = [], []
    for binding in identities['records']:
        ident, pid = binding['original_id'], binding['person_id']
        offset = ORIGINAL_RECORD_OFFSET + ident * ORIGINAL_RECORD_SIZE
        raw = rom[offset:offset + ORIGINAL_RECORD_SIZE]
        record_hash = sha256(raw).hexdigest()
        records.append(dict(original_id=ident, person_id=pid,
            transcribed_name=binding['transcribed_name'], rom_offset=offset,
            record_hex=raw.hex(' ').upper(), record_sha256=record_hash,
            virtue=raw[4], experience_raw=int.from_bytes(raw[6:8], 'little')))
        if pid is None:
            continue
        person = pool['people'][pid]
        if (person.get('virtue_design') or {}).get('status') != 'verified_original':
            person['previous_virtue_design'] = deepcopy(person['virtue_design'])
            person['previous_virtue_profile'] = dict(virtue=person['profile']['virtue'],
                basis=person['profile']['basis']['virtue'], configuration=person['configuration']['virtue'])
        previous = person['previous_virtue_profile']
        if previous['virtue'] != raw[4]:
            differences.append(dict(person_id=pid, name=person['name'], original_id=ident,
                previous=previous['virtue'], original=raw[4],
                previous_status=(person['previous_virtue_design'] or {}).get('status', 'legacy')))
        person['profile']['virtue'] = raw[4]
        person['profile']['basis']['virtue'] = 'verified_original_ROM_byte4; reviewed_exact_name_identity'
        person['configuration']['virtue'] = 'verified_original_ROM_value'
        person['virtue_design'] = dict(person_id=pid, name=person['name'], status='verified_original',
            virtue=raw[4], original_id=ident, rom_sha256=ORIGINAL_ROM_SHA256,
            rom_offset=offset + 4, record_sha256=record_hash,
            is_historical_fact=False, dimensions=None,
            identity_basis=binding['identity_basis'],
            design_rationale='採用已核對姓名身分的原版ROM「德」欄位；原版既有值優先於本作歷史評分及預設60。武、知仍採用已確定的SAN14轉換規則。',
            sources=[dict(work='三國志2超級版 NES ROM', section=f'武將記錄{ident}，+4德欄位',
                          reference='game/config/references/original-officer-stats.json')])
    reference = dict(schema='tk2-original-officer-stats-v1', rom_sha256=ORIGINAL_ROM_SHA256,
        record_offset=ORIGINAL_RECORD_OFFSET, record_size=ORIGINAL_RECORD_SIZE,
        field_policy='Only original virtue is applied; SAN14 martial/intellect and remake health/affinity/initialization remain unchanged.',
        identity_source='game/config/portrait-identity-map.json',
        identity_source_sha256=sha256(identity_path.read_bytes()).hexdigest(),
        identity_policy='Reviewed ROM name-glyph transcription and unique exact name/orthographic identity; no likeness, statistical, ordinal or runtime-ID joins.',
        **coverage,
        audit=dict(changed_people=len(differences),
                   prior_default_changes=sum(r['previous_status'] == 'configured_default' for r in differences),
                   prior_design_changes=sum(r['previous_status'] == 'configured_design' for r in differences),
                   unchanged_original_values=coverage['bound_people']-len(differences), differences=differences), records=records)
    validate_original_virtue(pool['people'], reference, identities)
    return pool, reference


if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('rom', type=Path, nargs='?')
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    if args.check:
        print(json.dumps(verify_retained_reference(args.rom.read_bytes() if args.rom else None),
                         ensure_ascii=False))
        raise SystemExit(0)
    if args.rom is None:
        parser.error('the archived import requires an explicit ROM; use --check for read-only evidence verification')
    pool, reference = import_stats(args.rom.read_bytes())
    outputs = {ROOT/'game/config/campaigns/people.json': pool,
               ROOT/'game/config/references/original-officer-stats.json': reference}
    for path, value in outputs.items():
        data = encode(value)
        path.write_text(data)
    print(json.dumps(dict(bound=reference['bound_people'], changed=reference['audit']['changed_people'],
                          check=args.check), ensure_ascii=False))
