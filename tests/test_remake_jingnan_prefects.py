"""The Red Cliffs opening keeps Jingnan's four named local prefects."""
from collections import Counter
import json
from pathlib import Path
import sys
import tempfile
import unittest

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / 'source'))
sys.path.insert(0, str(ROOT / 'game'))
from build_campaigns import load_sources
from remake.campaign import Campaign, Catalog
from remake import civil_staff
from remake.map_presentation import color_distance, faction_colors
from remake.session import CampaignSession, faction_officer_counts
from campaign_fixtures import advance_month


PREFECTS = (
    ('changsha', 'han_xuan', '韩玄', 'san14-candidate-0158', 157),
    ('wuling', 'jin_xuan', '金旋', 'san14-candidate-0223', 222),
    ('guiyang', 'zhao_fan', '赵范', 'san14-candidate-0654', 653),
    ('lingling', 'liu_du', '刘度', 'san14-candidate-0949', 948),
)


class JingnanPrefectTests(unittest.TestCase):
    @classmethod
    def setUpClass(cls):
        # Canonical sources, rather than a previously generated catalog, are
        # authoritative. A temporary file exercises the real Catalog/save path.
        # No roads are exercised here. Geometry's pinned source hashes are
        # regenerated by the release build after all scenario edits complete.
        _, sources = load_sources(timing=False)
        cls.data = next(row for row in sources if row['id'] == 'mainland208-10')
        cls.temp = tempfile.TemporaryDirectory(prefix='tk2-jingnan-')
        cls.path = Path(cls.temp.name) / '208-10.json'
        cls.path.write_text(json.dumps(cls.data, ensure_ascii=False))
        cls.catalog = Catalog(cls.path)
        cls.canonical_people = json.loads(
            (ROOT / 'game/config/campaigns/people.json').read_text())['people']

    @classmethod
    def tearDownClass(cls):
        cls.temp.cleanup()

    def test_four_prefects_have_their_own_city_ruler_and_existing_identity(self):
        game = Campaign(self.catalog)
        game.command('new', dict(faction='shu', seed=2026), 0)
        for city, faction, name, pid, ident in PREFECTS:
            with self.subTest(city=city):
                self.assertEqual(self.catalog.ids[pid], ident)
                self.assertEqual(self.catalog.name(ident), name)
                self.assertEqual(self.data['initial_owners'][city], faction)
                self.assertEqual(self.catalog.factions[faction]['city'], city)
                self.assertEqual(self.catalog.factions[faction]['captain'], name)
                self.assertEqual(self.data['faction_rulers'][faction], ident)
                self.assertEqual(game.state.extension['leaders'][faction], ident)
                self.assertIn(ident, game.state.cities[city].roster.officer_ids)
                self.assertTrue(game.state.officers[ident].alive)
                self.assertEqual(game.state.officers[ident].faction_id, faction)
                self.assertEqual(game.state.officers[ident].loyalty, 100)
                assignment = self.data['era_assignments'][pid]
                self.assertEqual((assignment['status'], assignment['city'],
                                  assignment['faction']), ('serving', city, faction))
                self.assertEqual(assignment['placement_review']['source_urls'],
                                 ['https://zh.wikisource.org/zh-hant/三國志/卷32'])

    def test_huang_zhong_still_serves_han_xuan_before_the_southern_campaign(self):
        pid = 'san14-candidate-0271'
        assignment = self.data['era_assignments'][pid]
        row = next(r for r in self.data['initial_officers'] if r['person_id'] == pid)
        self.assertEqual(row['city'], 'changsha')
        self.assertFalse(row['ruler'])
        self.assertEqual((assignment['faction'], assignment['city']),
                         ('han_xuan', 'changsha'))
        self.assertIn('三國志/卷36', assignment['placement_review']['source_urls'][0])
        self.assertIn('攸縣', assignment['placement_review']['note'])
        self.assertEqual(faction_officer_counts(self.catalog)['han_xuan'], 3)
        # Wei Yan's posting is separately marked as a Romance-compatible game
        # setting; it does not change Huang Zhong's primary-text evidence.
        self.assertEqual(self.data['era_assignments']['san14-candidate-0189']['faction'], 'han_xuan')
        self.assertEqual(assignment['placement_review']['historical_certainty'],
                         'primary_text_attested')

    def test_new_rulers_are_selectable_and_roundtrip_current_saves(self):
        for city, faction, _, _, ident in PREFECTS:
            with self.subTest(faction=faction):
                session = CampaignSession([self.path])
                preview = session.view()['catalog']['scenarios'][0]
                self.assertIn(faction, {row['id'] for row in preview['factions']})
                self.assertEqual(preview['initial_owners'][city], faction)
                self.assertGreater(preview['faction_officers'][faction], 0)
                session.command('new', dict(scenario='mainland208-10',
                                           faction=faction, seed=2026), 0)
                saved = session.export_save()
                session.load_save(saved, session.revision)
                self.assertEqual(session.game.state.player, faction)
                self.assertEqual(session.game.state.extension['leaders'][faction], ident)
                self.assertEqual(session.export_save(), saved)

    def test_han_xuan_is_not_automatically_killed_by_an_unattested208_death(self):
        person = self.catalog.by_id[157]
        design = person['chronology_design']
        self.assertIsNone(design['death_year'])
        self.assertEqual(design['retirement_year'], 230)
        self.assertEqual(design['precision']['retirement_year'],
                         'authorial_game_retirement_boundary_not_historical_death')
        game = Campaign(self.catalog)
        game.command('new', dict(faction='han_xuan', seed=2026), 0)
        for _ in range(3):
            advance_month(game)
            # Direct calendar-service calls omit transaction-level cleanup.
            civil_staff.synchronize(game, game.state, checks=False)
            game._reconcile_factions(game.state)
        self.assertEqual((game.state.year, game.state.month), (209, 1))
        self.assertTrue(game.state.officers[157].alive)
        self.assertEqual(game.state.extension['leaders']['han_xuan'], 157)
        self.assertIn(157, game.state.cities['changsha'].roster.officer_ids)
        game.validate(game.state)

    def test_rosters_counts_and_all_existing_profiles_and_portrait_bindings_agree(self):
        serving = {row['person_id'] for row in self.data['initial_officers']}
        free = {row['person_id'] for row in self.data['initial_free_officers']}
        self.assertFalse(serving & free)
        self.assertEqual(len(serving), len(self.data['initial_officers']))
        self.assertEqual(self.data['coverage']['initial_serving'], len(serving))
        self.assertEqual(self.data['coverage']['initial_free'], len(free))
        self.assertEqual(len(self.data['people']), 1052)
        self.assertEqual(set(self.catalog.ids), set(self.canonical_people))
        portraits = json.loads((ROOT / 'game/assets/portraits/index.json').read_text())['people']
        for person in self.data['people']:
            pid = person['person_id']
            self.assertEqual(person['profile'], self.canonical_people[pid]['profile'])
            self.assertEqual(person['runtime_id'], self.canonical_people[pid]['runtime_id'])
            self.assertIn(pid, portraits)
        actual = faction_officer_counts(self.catalog)
        self.assertEqual(actual, {row['id']: row['initial_officers']
                                  for row in self.data['factions']})
        self.assertEqual(self.data['placement_completion']['reference_classes'],
                         dict(Counter(a['placement_review']['historical_certainty']
                                      for a in self.data['era_assignments'].values())))
        self.assertEqual(self.data['placement_completion']['bases'],
                         dict(Counter(a['placement_review']['basis']
                                      for a in self.data['era_assignments'].values())))

    def test_reviewed_jingnan_rosters_reuse_existing_ids_with_explicit_novel_provenance(self):
        expected = {
            'han_xuan': {f'san14-candidate-{i:04d}' for i in (158, 271, 189)},
            'jin_xuan': {f'san14-candidate-{i:04d}' for i in (223, 204)},
            'zhao_fan': {f'san14-candidate-{i:04d}' for i in (654, 668, 831)},
            'liu_du': {f'san14-candidate-{i:04d}' for i in (949, 934, 228)},
        }
        actual = {side: {row['person_id'] for row in self.data['initial_officers']
                         if self.data['initial_owners'][row['city']] == side}
                  for side in expected}
        self.assertEqual(actual, expected)
        self.assertEqual({side: len(members) for side, members in actual.items()},
                         {'han_xuan': 3, 'jin_xuan': 2, 'zhao_fan': 3, 'liu_du': 3})

        portraits = json.loads((ROOT / 'game/assets/portraits/index.json').read_text())['people']
        self.assertEqual(len(self.canonical_people), 1052)
        self.assertEqual(set(self.catalog.ids), set(self.canonical_people))
        self.assertEqual(set(portraits), set(self.canonical_people))
        game = Campaign(self.catalog)
        game.command('new', dict(faction='han_xuan', seed=2026), 0)
        for city, side, _, _, _ in PREFECTS:
            with self.subTest(faction=side):
                self.assertEqual(set(game.state.cities[city].roster.officer_ids),
                                 {self.catalog.ids[pid] for pid in expected[side]})
                for pid in expected[side]:
                    self.assertEqual(self.catalog.ids[pid], self.canonical_people[pid]['runtime_id'])
                    self.assertTrue((ROOT / 'game' / portraits[pid]['path'].lstrip('/')).is_file())

        # The novel supplies these affiliations, while all six identities and
        # their portraits were already in the pool. Do not label them as
        # independently attested historical garrisons or introduce new people.
        for ident in (189, 204, 228, 668, 831, 934):
            pid = f'san14-candidate-{ident:04d}'
            with self.subTest(person=pid):
                review = self.data['era_assignments'][pid]['placement_review']
                self.assertEqual(review['historical_certainty'], 'novel_compatible_affiliation')
                self.assertIn('演義兼容', review['note'])
                self.assertIn('不冒稱正史', review['note'])
                self.assertEqual(set(review['source_urls']), {
                    'https://zh.wikisource.org/wiki/三國演義/第052回',
                    'https://zh.wikisource.org/wiki/三國演義/第053回',
                })

    def test_map_colors_distinguish_every_new_faction_and_linjiang_is_cao_caos(self):
        palette = faction_colors(self.catalog)
        colors = [palette[key] for key in self.catalog.factions]
        self.assertEqual(len(colors), len(set(colors)))
        for index, color in enumerate(colors):
            for other in colors[index + 1:]:
                self.assertGreaterEqual(color_distance(color, other), 29)
        self.assertEqual(self.data['initial_owners']['yidu'], 'wei')


if __name__ == '__main__':
    unittest.main()
